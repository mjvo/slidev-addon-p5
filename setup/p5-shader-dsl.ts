export const getShaderDslBridgeScript = (instanceName: string): string => {
  // Shader-builder callbacks execute in a strands-specific scope where helpers
  // like `mix()` are looked up as globals rather than through the sketch
  // instance. Bridge only the shader DSL names here so regular sketch code does
  // not inherit the broad false-positive rewrites that broke normal globals.
  return SHADER_DSL_FUNCTIONS
    .map((name) => `window.${name} = (...args) => ${instanceName}.${name}(...args);`)
    .join("\n");
};
